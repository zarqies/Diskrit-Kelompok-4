from itertools import permutations
import networkx as nx
import matplotlib.pyplot as plt

lokasi = {
    "A": "Kantor Sales",
    "B": "Toko Mawar",
    "C": "Toko Melati",
    "D": "Toko Anggrek",
    "E": "Toko Cempaka",
    "F": "Toko Kenanga"
}
jarak = {
    ("A", "B"): 5,
    ("A", "C"): 8,
    ("A", "D"): 6,
    ("A", "E"): 9,
    ("A", "F"): 7,
    ("B", "C"): 4,
    ("B", "D"): 7,
    ("B", "E"): 6,
    ("B", "F"): 8,
    ("C", "D"): 3,
    ("C", "E"): 5,
    ("C", "F"): 6,
    ("D", "E"): 4,
    ("D", "F"): 5,
    ("E", "F"): 3,
}

def cari_jarak(a, b):
  return jarak.get((a, b), jarak.get((b, a), 0))

awal = "A"
toko = [kode for kode in lokasi if kode != awal]

jarak_minimum = float("inf")
rute_terbaik = []

for urutan in permutations(toko):
  rute = [awal] + list(urutan) + [awal]
  total = 0

  for i in range(len(rute) - 1):
    total += cari_jarak(rute[i], rute[i + 1])

  if total < jarak_minimum:
    jarak_minimum = total
    rute_terbaik = rute

print("===== OPTIMASI RUTE SALES =====")
print("\nUrutan kunjungan:")

urutan_nama = [lokasi[kode] for kode in rute_terbaik]
print(" -> ".join(urutan_nama))

print("\nTotal jarak minimum:", jarak_minimum, "km")

G = nx.Graph()

for kode, nama in lokasi.items():
    G.add_node(kode, nama=nama)

for (a, b), nilai in jarak.items():
    G.add_edge(a, b, weight=nilai)

posisi = nx.spring_layout(G, seed=10)

nx.draw(
    G, posisi,
    with_labels=True,
    node_color="skyblue",
    node_size=2000,
    font_size=12
)

label_jarak = nx.get_edge_attributes(G, "weight")
nx.draw_networkx_edge_labels(
    G, posisi,
    edge_labels=label_jarak
)

label_jarak = nx.get_edge_attributes(G, "weight")

nx.draw_networkx_edge_labels(
    G, posisi,
    edge_labels=label_jarak
)

plt.title("Graph Optimasi Rute Kunjungan Sales")
plt.show()